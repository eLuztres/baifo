export type AdminTexts = typeof ES;

const TEXTS: Partial<Record<Locale, AdminTexts>> = { es: ES, en: EN, it: IT };

export const adminTexts = (locale: Locale): AdminTexts => TEXTS[locale] ?? EN;

export const fillText = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
